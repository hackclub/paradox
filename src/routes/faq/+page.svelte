                "\n" +
                "* inflating your hours on hackatime to receive a higher payout\n" +
                "* submitting a template/guide with no unique changes made to it\n" +
                "* submitting entirely AI generated or copied code and claiming it as your own\n" +
                "\n" +
                "The consequences of committing fraud. includes being banned from paradox, and in sever cases, being banned from Hackatime, hence being banned from all Hack Club events.\n",
        },
        {
            q: "Can I work with others?",
            a: "Yes you can! We encourage you to work with others on cool projects, just make sure that you individually log your hours on Hackatime and submit your projects separately.\n",
        },
        {
            q: "Can I use AI?",
            a: "AI is not allowed in any capacity for creating any music or art for your project. AI can be used for help outside of that, such as for writing code, or research, however only up to 30% of your code can be generated by AI. If AI slop is submitted it will be automatically rejected, and it may lead to being banned from Paradox.\n",
        },
    ]

    let selected = $state(0);
</script>

<main
    class="main w-full min-h-screen relative overflow-hidden"
    bind:this={main}
>

    <div class="absolute top-0 left-0 p-4 sm:p-6">
        <button onclick={() => (window.location.href = "/")}>
            <img
                    src="/images/faq/faq-btn.png"
                    class="min-w-52 w-64 max-w-[20vw] transition-all duration-300 ease-in-out hover:opacity-60 cursor-pointer"
                    alt="Home Button"
            />
        </button>
    </div>

    <button class="absolute bottom-0 left-1/2 -translate-x-1/2 cursor-auto" onclick={animateBook}>
        <img
                src="/images/faq/faq-book.png"
                class="w-[50rem] transition-all duration-700 ease-in-out hover:opacity-80 cursor-pointer"
                class:openBook={isOpen}
                ontransitionend={handleBookTransitionEnd}
                bind:this={bookClosed}
                alt="FAQ Playbook"
        />
    </button>

    <div
        class="opened-book-wrapper absolute bottom-0 left-1/2 -translate-x-1/2"
        class:hidden={!showPages}
        bind:this={bookOpened}
    >
        <div class="opened-book flex flex-row">
            <div
                class="bg-[#EDEAE1] min-h-[20rem] h-[50rem] min-w-[20rem] w-[38rem] max-w-[42rem] border-r-2 border-black rounded-lg p-10"
            >
                <div class="h-4 w-[100%] bg-black"></div>
                <div class="h-1 w-[100%] bg-black mt-2"></div>
                <h1 style="font-family: 'Bethany, serif'" class="text-8xl">FAQ</h1>
                <div class="h-1 w-[30%] bg-black mt-6"></div>
                {#each faqItems as item, i}
                        <button
                                class="q text-3xl mt-6 text-left hover:font-bold"
                                onclick={() => (selected = i)}
                                class:under={selected === i}
                                style="font-family: 'Bethany', serif"
                        >
                            {item.q}
                        </button>
                        <br>
                        {#if item.q === "Do I need to have any prior experience?"}<br>{/if}

                {/each}
                <div class="h-1 w-[30%] bg-black mt-6"></div>
                <div class="flex flex-row items-center gap-3 mt-16">
                    <img
                        src="images/faq/faq-logo.png"
